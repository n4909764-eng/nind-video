export const getTranslation = (lang, key) => {
  return translations[lang]?.[key] || translations.en[key] || key;
};

// Helper to get current language code from localStorage (default: en)
export const getCurrentLang = () => {
  if (typeof window === "undefined") return "en";
  return localStorage.getItem("slind_language") || "en";
};

// Convenience: translate a key using current language (handy for toast messages)
export const tr = (key) => getTranslation(getCurrentLang(), key);

// Save language and notify all components in real-time
export const setAppLanguage = (langCode) => {
  if (typeof window !== "undefined") {
    localStorage.setItem("slind_language", langCode);
    window.dispatchEvent(new CustomEvent("slind_language_changed", { detail: langCode }));
  }
};

// React hook to subscribe to language changes across all pages
export const useAppLanguage = () => {
  const [lang, setLang] = useState(getCurrentLang());

  useEffect(() => {
    const handleUpdate = () => {
      setLang(getCurrentLang());
    };
    window.addEventListener("slind_language_changed", handleUpdate);
    window.addEventListener("storage", handleUpdate);
    return () => {
      window.removeEventListener("slind_language_changed", handleUpdate);
      window.removeEventListener("storage", handleUpdate);
    };
  }, []);

  const t = (key) => getTranslation(lang, key);
  return { lang, t };
};
